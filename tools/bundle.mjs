/**
 * bundle.mjs — produce standalone.html: the whole app in one file.
 *
 *   node tools/bundle.mjs
 *
 * The deployed site uses the normal multi-file layout; this build exists so the
 * viewer can be opened straight off disk (file://) or emailed as a single file,
 * where ES module fetches would otherwise be blocked by CORS. Three.js still
 * comes from the CDN via the import map, which file:// pages are allowed to load.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Dependency order: leaves first, entry point last.
const MODULES = ['extractor.js', 'volume.js', 'effects.js', 'export.js', 'viewer.js', 'main.js'];

const RE_LOCAL_IMPORT = /^import\s[\s\S]*?from\s*['"]\.\/[^'"]+['"];[ \t]*\r?\n/gm;
const RE_BARE_IMPORT = /^import\s[\s\S]*?from\s*['"]three[^'"]*['"];[ \t]*\r?\n/gm;
const RE_EXPORT_KEYWORD = /^export\s+(?=(?:class|function|async|const|let|var)\b)/gm;

const html = await readFile(join(root, 'index.html'), 'utf8');
const css = await readFile(join(root, 'src', 'styles.css'), 'utf8');

const sources = [];
for (const name of MODULES) {
  let code = await readFile(join(root, 'src', name), 'utf8');
  code = code.replace(RE_LOCAL_IMPORT, '');
  code = code.replace(RE_BARE_IMPORT, '');
  code = code.replace(RE_EXPORT_KEYWORD, '');
  sources.push(`/* ===== src/${name} ===== */\n${code.trim()}\n`);
}

const bundle = [
  `import * as THREE from 'three';`,
  `import { OrbitControls } from 'three/addons/controls/OrbitControls.js';`,
  '',
  ...sources,
].join('\n');

let out = html
  .replace(
    /<link rel="stylesheet" href="\.\/src\/styles\.css"\s*\/?>/,
    `<style>\n${css.trim()}\n</style>`
  )
  .replace(
    /<script type="module" src="\.\/src\/main\.js"><\/script>/,
    `<script type="module">\n${bundle}\n</script>`
  );

if (out === html || out.includes('href="./src/styles.css"') || out.includes('src="./src/main.js"')) {
  throw new Error('Bundle failed: index.html did not match the expected link/script tags.');
}

out = out.replace(
  '<title>',
  '<!-- Generated by tools/bundle.mjs — edit src/, not this file. -->\n<title>'
);

await writeFile(join(root, 'standalone.html'), out, 'utf8');
console.log(`standalone.html written (${(out.length / 1024).toFixed(0)} KB)`);
